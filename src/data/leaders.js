export function getLeaderBySlug(slug) {
  return LEADERS.find((leader) => leader.slug === slug) || null;
}

export function getLeaderInitials(name) {
  return name
    .split(' ')
    .map((word) => word[0])
    .filter(Boolean)
    .slice(0, 2)
    .join('')
    .toUpperCase();
}
